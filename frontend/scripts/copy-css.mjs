#!/usr/bin/env node
// Emit the single self-contained stylesheet that the Axum server embeds.
//
// `astro build` (build:astro) compiles src/styles/global.css through
// @tailwindcss/vite into ONE flat asset in dist/_astro (cssCodeSplit is off,
// minification is off, assets are never base64-inlined). This script picks
// that asset, proves it is self-contained, and commits it to
// crates/shorten-web/assets/styles.css, the path the templates request at
// GET /assets/styles.css.
//
// The contract the Rust server relies on: one readable file, no @import,
// no url(...), no remote font reference — the CSP is `default-src 'self'`.

import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, '..');
const repo = path.resolve(frontend, '..');
const dist = path.join(frontend, 'dist');
const target = path.join(repo, 'crates', 'shorten-web', 'assets', 'styles.css');

async function stylesheetsIn(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await stylesheetsIn(full)));
    } else if (entry.name.endsWith('.css')) {
      found.push(full);
    }
  }
  return found;
}

const sheets = await stylesheetsIn(dist);
if (sheets.length === 0) {
  console.error(
    `build:css — no stylesheet found under ${path.relative(repo, dist)}\n` +
      '  run astro build first (pnpm -C frontend run build:astro)',
  );
  process.exit(1);
}
if (sheets.length > 1) {
  console.error(
    `build:css — expected exactly one stylesheet, found ${sheets.length}:\n` +
      sheets.map((file) => `  ${path.relative(repo, file)}`).join('\n'),
  );
  console.error('  cssCodeSplit must stay false in astro.config.mjs');
  process.exit(1);
}

const source = sheets[0];
const css = await readFile(source, 'utf8');

const violations = [];
if (/@import\b/.test(css)) violations.push('@import statement (the artifact must be self-contained)');
if (/@import\s+url\(/.test(css)) violations.push('@import url()');
if (/\burl\(\s*['"]?(https?:)?\/\//.test(css)) violations.push('remote url() reference (CSP is default-src \'self\')');
if (/\burl\(\s*['"]?data:/.test(css)) violations.push('data: url() reference');
if (/@font-face/.test(css)) violations.push('@font-face with a src url (fonts must come from system fallbacks)');
if (css.trim().length < 4000) violations.push(`stylesheet looks truncated (${css.trim().length} bytes)`);

if (violations.length > 0) {
  console.error(`build:css — stylesheet is not self-contained: ${path.relative(repo, source)}`);
  for (const violation of violations) console.error(`  - ${violation}`);
  process.exit(1);
}

const header = `/* Generated by \`pnpm -C frontend run build\` (frontend/scripts/copy-css.mjs).
   Source layers: frontend/src/styles/{design-tokens,global,components,utilities}.css
   Compiled through @tailwindcss/vite; committed so \`cargo build\` needs no Node.
   Served by Axum at GET /assets/styles.css (rust-embed, immutable cache).
   Edit the layers in frontend/src/styles, never this file. */

`;

await mkdir(path.dirname(target), { recursive: true });
await writeFile(target, header + css, 'utf8');

const bytes = Buffer.byteLength(header + css, 'utf8');
console.log(
  `build:css — wrote crates/shorten-web/assets/styles.css (${bytes} bytes, ${css.split('\n').length} lines)`,
);
